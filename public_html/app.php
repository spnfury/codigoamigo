function debug_log($message, $data = null)
{
    $log = date('Y-m-d H:i:s') . " - " . $message;
    if ($data !== null) {
        $log .= "\nData: " . print_r($data, true);
    }
    if ($data instanceof Exception) {
        $log .= "\nStack trace: " . $data->getTraceAsString();
    }
    error_log($log . "\n", 3, __DIR__ . '/debug.log');
}

