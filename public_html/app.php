    $app->post('/verify', function ($request, $response) {
        debug_log('API /verify called');
        debug_log('Request headers:', getallheaders());
        debug_log('Request body:', file_get_contents('php://input'));

        try {
            $data = $request->getParsedBody();
            debug_log('Parsed request data:', $data);

            if (!$data) {
                debug_log('No data received in request');
                return $response->withJson([
                    'error' => 'No data received'
                ], 400);
            }

            $phone = $data['phone'] ?? '';
            debug_log('Phone number:', $phone);

            if (!$phone) {
                debug_log('Phone number missing');
                return $response->withJson([
                    'error' => 'Phone number is required'
                ], 400);
            }

            debug_log('Looking up user with phone:', $phone);
            $usuario = getObjectUser('telefono', $phone);
            debug_log('User lookup result:', $usuario);

            if ($usuario) {
                return $response->withJson([
                    'success' => true,
                    'user_id' => (string) $usuario['_id'],
                    'username' => $usuario['username']
                ]);
            }

            return $response->withJson([
                'error' => 'User not found'
            ], 404);

        } catch (Exception $e) {
            debug_log('Exception in /verify:', $e);
            return $response->withJson([
                'error' => 'Internal server error',
                'message' => $e->getMessage(),
                'file' => $e->getFile(),
                'line' => $e->getLine()
            ], 500);
        }
    });

    // Obtener códigos de un usuario
    $app->get('/codes', function ($request, $response) {
        $userId = $request->getHeaderLine('user_id');

        if (!$userId) {
            return $response->withJson([
                'error' => 'User ID is required'
            ], 400);
        }

        try {
            // Obtener códigos del usuario
            $array_filtro = [
                "id_usuario" => $userId,
                "estado" => array('$in' => [0, -1, 1])
            ];

            $array_opciones = [
                "limit" => 50,
                "sort" => ["_id" => -1]
            ];

            $codigos = get_all_listado_codigos_array($array_filtro, $array_opciones);

            // Formatear respuesta
            $formatted_codes = [];
            foreach ($codigos['results'] as $codigo) {
                $marca = getObjectMarca('nombre_clave', $codigo['marca']);

                $formatted_codes[] = [
                    'id' => (string) $codigo['_id'],
                    'game' => $marca['nombre'] ?? $codigo['marca'],
                    'code' => $codigo['codigo'],
                    'date' => date('Y-m-d', strtotime($codigo['fecha'])),
                    'description' => $codigo['descripcion'],
                    'status' => $codigo['estado']
                ];
            }

            return $response->withJson($formatted_codes);

        } catch (Exception $e) {
            return $response->withJson([
                'error' => 'Internal server error'
            ], 500);
        }
    });

    // Añadir nuevo código
    $app->post('/codes', function ($request, $response) {
        $data = $request->getParsedBody();
        $userId = $request->getHeaderLine('user_id');

        if (!$userId || !isset($data['marca']) || !isset($data['codigo'])) {
            return $response->withJson([
                'error' => 'Missing required fields'
            ], 400);
        }

        try {
            $newCode = [
                'marca' => $data['marca'],
                'codigo' => $data['codigo'],
                'descripcion' => $data['descripcion'] ?? '',
                'id_usuario' => $userId
            ];

            $result = addNewCode($newCode, $userId);

            if ($result) {
                return $response->withJson([
                    'success' => true,
                    'code_id' => (string) $result
                ]);
            }

            return $response->withJson([
                'error' => 'Failed to add code'
            ], 500);

        } catch (Exception $e) {
            return $response->withJson([
                'error' => 'Internal server error'
            ], 500);
        }
    });

    // Modificar código existente
    $app->put('/codes/{id}', function ($request, $response, $args) {
        $codeId = $args['id'];
        $userId = $request->getHeaderLine('user_id');
        $data = $request->getParsedBody();

        if (!$userId || !$codeId) {
            return $response->withJson([
                'error' => 'Missing required fields'
            ], 400);
        }

        try {
            // Verificar que el código pertenece al usuario
            $codigo = getCodeByID(new \MongoDB\BSON\ObjectId($codeId));

            if (!$codigo || $codigo['id_usuario'] !== $userId) {
                return $response->withJson([
                    'error' => 'Code not found or unauthorized'
                ], 404);
            }

            // Actualizar código
            $updateData = [
                'codigo_id' => $codeId,
                'codigo' => $data['codigo'] ?? $codigo['codigo'],
                'descripcion' => $data['descripcion'] ?? $codigo['descripcion'],
                'marca' => $data['marca'] ?? $codigo['marca']
            ];

            $result = updateExistingCode($updateData, $userId);

            if ($result) {
                return $response->withJson([
                    'success' => true
                ]);
            }

            return $response->withJson([
                'error' => 'Failed to update code'
            ], 500);

        } catch (Exception $e) {
            return $response->withJson([
                'error' => 'Internal server error'
            ], 500);
        }
    });

});






